package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	in := flag.String("in", "", "input BPF object")
	out := flag.String("out", "", "output Go source")
	pkg := flag.String("pkg", "ebpf", "Go package name")
	name := flag.String("var", "bpfObject", "Go variable name")
	flag.Parse()

	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "bpfgen: -in and -out are required")
		os.Exit(2)
	}

	data, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "bpfgen: read: %v\n", err)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by source/tools/bpfgen. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: %s\n\n", filepath.ToSlash(*in))
	fmt.Fprintf(&b, "package %s\n\n", *pkg)
	fmt.Fprintf(&b, "var %s = []byte{\n", *name)
	for i, v := range data {
		if i%12 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(&b, "0x%02x, ", v)
		if i%12 == 11 {
			b.WriteString("\n")
		}
	}
	if len(data)%12 != 0 {
		b.WriteString("\n")
	}
	b.WriteString("}\n")

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "bpfgen: mkdir: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "bpfgen: write: %v\n", err)
		os.Exit(1)
	}
}
